    os.makedirs(OUT, exist_ok=True)

    dst = os.path.join(OUT, "syllabus_tree.json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump({
            "名称": "408 考纲知识点树",
            "来源": "2026 年计算机学科专业基础综合考试大纲(官方考察内容结构)",
            "层级": "L1 学科 / L2 章 / L3 节 / L4 考点",
            "规模": {"学科": n_sub, "章": n_ch, "节": n_sec, "考点": n_pt},
            "编码规则": "<学科>-<章>-<节>-<考点>, 学科码 DS/CO/OS/CN",
            "待补字段": ["exam_freq", "depends_on", "掌握要求等级", "aliases"],
            "学科": tree,
        }, f, ensure_ascii=False, indent=2)

    md = os.path.join(OUT, "syllabus_draft.md")
    open(md, "w", encoding="utf-8").write(draft_md(tree))

    print(f"学科 {n_sub} / 章 {n_ch} / 节 {n_sec} / 考点 {n_pt}")
    for s in tree:
        c = len(s["children"])
