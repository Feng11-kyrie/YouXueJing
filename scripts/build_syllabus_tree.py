def build():
    tree = []
    for code, name, score, chapters in SYLLABUS:
        ch_nodes = []
        for ci, (ch_name, sections) in enumerate(chapters, start=1):
            sec_nodes = []
            for si, (sec_name, points) in enumerate(sections, start=1):
                pt_nodes = []
                for pi, p_name in enumerate(points, start=1):
                    pid = f"{code}-{ci:02d}-{si:02d}-{pi:02d}"
                    pt_nodes.append({
                        "id": pid, "level": 4, "parent": f"{code}-{ci:02d}-{si:02d}",
                        "name_official": p_name, "name_plain": p_name,
                        "aliases": [], "exam_freq": None, "depends_on": [],
                    })
                sid = f"{code}-{ci:02d}-{si:02d}"
                sec_nodes.append({
                    "id": sid, "level": 3, "parent": f"{code}-{ci:02d}",
                    "name_official": sec_name, "name_plain": PLAIN.get(sid, sec_name),
                    "aliases": [], "exam_freq": None, "depends_on": [],
                    "children": pt_nodes,
                })
            cid = f"{code}-{ci:02d}"
            ch_nodes.append({
                "id": cid, "level": 2, "parent": code,
                "name_official": ch_name, "name_plain": ch_name,
                "aliases": [], "exam_freq": None, "depends_on": [],
                "children": sec_nodes,
            })
        tree.append({
            "id": code, "level": 1, "parent": None,
            "name_official": name, "name_plain": name, "aliases": [],
            "满分": score, "children": ch_nodes,
        })
    return tree


def stats(tree):
    n_ch = sum(len(s["children"]) for s in tree)
    n_sec = sum(len(c["children"]) for s in tree for c in s["children"])
    n_pt = sum(len(x["children"]) for s in tree for c in s["children"] for x in c["children"])
    return len(tree), n_ch, n_sec, n_pt


def draft_md(tree):
    L = ["# 408 考纲知识点树 · 草案（待你确认）", "",
         "来源: **2026 年《计算机学科专业基础综合考试大纲》**官方考察内容结构(逐条照录)",
         "",
         "规模: **4 学科 / 24 章 / 116 节 / 213 考点**", "",
         "> 说明: L4「考点」= 大纲里带 1./2./3. 编号的条目。没有编号细目的节本身就是叶子。",
         "> `id` 用语义化编码(如 `DS-03-02-01`),**不用名字做 key** —— 条目名会改、会重名。",
         "> 每节同时保留**考纲原文名**和**通俗名**(UI 展示用)。",
         "> 待补: 每考点的`掌握/理解/了解`要求等级(网页版大纲未含, 需官方 PDF)、`exam_freq`、`depends_on`。",
         ""]
    for s in tree:
        L.append(f"## {s['name_official']}（{s['满分']} 分 · id `{s['id']}`）")
        L.append("")
        for c in s["children"]:
            L.append(f"### {c['name_official']}　`{c['id']}`")
            L.append("")
            for sec in c["children"]:
                plain = f"　→ 通俗名: **{sec['name_plain']}**" if sec["name_plain"] != sec["name_official"] else ""
                L.append(f"- **{sec['name_official']}**　`{sec['id']}`{plain}")
                for p in sec["children"]:
                    L.append(f"    - {p['name_official']}　`{p['id']}`")
            L.append("")
    return "\n".join(L)


